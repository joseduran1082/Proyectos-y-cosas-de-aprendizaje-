CREATE TRIGGER CONTROL_STOCK BEFORE INSERT ON USO_RECANVIS
FOR EACH ROW
BEGIN
	DECLARE STOCK_ACTUAL INT;
    SELECT QUANTITAT INTO STOCK_ACTUAL FROM RECANVIS
    WHERE CODI_RECANVI = NEW.CODI_RECANVI;
    
	IF NEW.QUANTITAT > STOCK_ACTUAL THEN
		SET NEW.QUANTITAT = STOCK_ACTUAL;
       /* SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '¡Epa loco! No hay tanto stock para este repuesto';*/
	END IF;
END //
