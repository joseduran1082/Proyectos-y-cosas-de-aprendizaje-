DROP DATABASE IF EXISTS TALLER_MECANICO;
CREATE DATABASE TALLER_MECANICO;
USE TALLER_MECANICO;

-- Tabla de Repuestos (Recanvis)
CREATE TABLE RECANVIS (
    CODI_RECANVI INT PRIMARY KEY,
    NOM VARCHAR(50),
    MODEL_COTXE VARCHAR(50),
    PREU_BASE DOUBLE,
    QUANTITAT INT,
    PREU_TOTAL_IVA DOUBLE,
    ESTADO_STOCK VARCHAR(20)
);


-- Tabla de Auditoría (Bitácora)
CREATE TABLE LOG_INVENTARI (
    ID_LOG INT AUTO_INCREMENT PRIMARY KEY,
    DATA_MOVIMENT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    USUARI VARCHAR(50) NOT NULL,
    DESCRIPCIO VARCHAR(100) NOT NULL
);

-- Tabla de Uso de Repuestos en reparaciones
CREATE TABLE USO_RECANVIS (
    ID_USO INT AUTO_INCREMENT PRIMARY KEY,
    CODI_RECANVI INT,
    QUANTITAT INT,
    DATA_US DATE
);
