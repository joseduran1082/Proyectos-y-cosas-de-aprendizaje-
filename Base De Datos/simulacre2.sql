DELIMITER //
CREATE FUNCTION ESTADO_STOCK(QUANTITAT INT)
RETURNS VARCHAR(20) DETERMINISTIC
BEGIN
	IF QUANTITAT = 0 THEN
		RETURN 'CRITICO COMPRAR YA';
	ELSEIF QUANTITAT >= 1 AND QUANTITAT <=5 THEN
		RETURN 'PILAS QUEDA POCO';
	ELSE 
		RETURN 'ESTAMOS BIEN';
	END IF;
    END //
DELIMITER ;
