PREU_FINAL DOUBLE
);


DELIMITER //
CREATE FUNCTION SIGNE(NUM INT)
RETURNS VARCHAR(20) DETERMINISTIC
BEGIN
    IF NUM < 0 THEN
		RETURN 'NEGATIU';
	ELSEIF NUM > 0 THEN
		RETURN 'POSITIU';
	ELSE
		RETURN 'ZERO';
	END IF;
		
END //
DELIMITER ;

