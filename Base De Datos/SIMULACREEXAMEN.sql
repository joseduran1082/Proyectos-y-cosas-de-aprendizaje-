DELIMITER //

CREATE FUNCTION PREU_FINAL(PREU DOUBLE, DESCOMPTE INT)
RETURNS DOUBLE DETERMINISTIC
BEGIN
	RETURN PREU - ((PREU * DESCOMPTE) / 100);
END // 
DELIMITER ;

