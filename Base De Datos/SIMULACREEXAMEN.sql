CREATE TABLE ALUMNE (
NOTA DOUBLE,
QUAL_NOTA VARCHAR(20),
NOM VARCHAR(20),
COGNOM VARCHAR(20),
APTE VARCHAR(20),
BONO VARCHAR(20)

);


DELIMITER //
CREATE FUNCTION QUALIFICACIO(NOTA DOUBLE)
RETURNS VARCHAR(20) DETERMINISTIC
BEGIN 
	 IF NOTA >= 9 THEN
        RETURN 'EXCELENT';
    ELSEIF NOTA >= 7 THEN
        RETURN 'NOTABLE';
    ELSEIF NOTA >= 5 THEN
        RETURN 'BE';
    ELSE
        RETURN 'INSUFICIENT';
    END IF;

END //
DELIMITER ;

INSERT INTO ALUMNE (NOTA, QUAL_NOTA) VALUES (5, QUALIFICACIO(5));

SELECT * FROM ALUMNE;


DELIMITER // 
CREATE FUNCTION CALCULA_BONO(NOTA double)
RETURNS VARCHAR(50) DETERMINISTIC
BEGIN
	IF NOTA >= 9 THEN
		RETURN '5O PALOS';
	ELSEIF NOTA >= 7 THEN
		RETURN '20 PALOS';
	ELSE
		RETURN 'NADA PAPA';
	END IF;

END //
DELIMITER ;

